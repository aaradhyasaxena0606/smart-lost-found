-- ============================================================================
-- 004_categories.sql
-- Lookup table for item categories (keeps `items` free of repeated text, 3NF).
-- ============================================================================

CREATE TABLE categories (
  category_id INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(80)  NOT NULL,
  description VARCHAR(255),
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),

  CONSTRAINT categories_name_key    UNIQUE (name),
  CONSTRAINT categories_name_len_chk CHECK (char_length(btrim(name)) BETWEEN 2 AND 80)
);

COMMENT ON TABLE categories IS 'Normalized category lookup referenced by items.category_id.';

CREATE TRIGGER trg_categories_set_updated_at
  BEFORE UPDATE ON categories
  FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();
