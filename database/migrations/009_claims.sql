-- ============================================================================
-- 009_claims.sql
-- Ownership claims against found items, plus administrator review fields.
-- ============================================================================

CREATE TABLE claims (
  claim_id        INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id         INTEGER      NOT NULL,
  claimant_id     INTEGER      NOT NULL,
  claim_message   TEXT         NOT NULL,
  -- Sensitive claimant evidence. Access-restricted and never returned by the
  -- API (spec 16); administrators verify ownership with the item's private
  -- verification hint plus the claim message instead. See docs/security.md.
  private_evidence VARCHAR(2000),
  status          VARCHAR(16)  NOT NULL DEFAULT 'pending',
  reviewed_by     INTEGER,
  reviewed_at     TIMESTAMPTZ,
  review_reason   VARCHAR(1000),
  created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),

  CONSTRAINT claims_item_fk     FOREIGN KEY (item_id)
    REFERENCES items (item_id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT claims_claimant_fk FOREIGN KEY (claimant_id)
    REFERENCES users (user_id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT claims_reviewer_fk FOREIGN KEY (reviewed_by)
    REFERENCES users (user_id) ON DELETE SET NULL ON UPDATE CASCADE,

  CONSTRAINT claims_status_chk CHECK (status IN ('pending', 'approved', 'rejected', 'withdrawn')),
  CONSTRAINT claims_message_len_chk CHECK (char_length(btrim(claim_message)) BETWEEN 10 AND 2000),
  CONSTRAINT claims_evidence_len_chk CHECK (private_evidence IS NULL OR char_length(private_evidence) <= 2000),

  -- FR-19 / spec 16: an administrator can never review their own claim.
  CONSTRAINT claims_no_self_review_chk CHECK (reviewed_by IS NULL OR reviewed_by <> claimant_id),

  -- A decided claim must carry reviewer + timestamp; pending/withdrawn must not.
  CONSTRAINT claims_review_consistency_chk CHECK (
    (status IN ('approved', 'rejected')) = (reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)
  ),
  -- FR-20: a rejection always records a reason.
  CONSTRAINT claims_reject_reason_chk CHECK (status <> 'rejected' OR review_reason IS NOT NULL)
);

COMMENT ON TABLE  claims IS 'Ownership claims for found items and their administrative review outcome.';
COMMENT ON COLUMN claims.private_evidence IS 'Sensitive. Excluded from every API response payload.';
COMMENT ON COLUMN claims.reviewed_by IS 'Administrator who decided the claim; may not equal claimant_id.';

CREATE TRIGGER trg_claims_set_updated_at
  BEFORE UPDATE ON claims
  FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();
