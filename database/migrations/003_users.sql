-- ============================================================================
-- 003_users.sql
-- Accounts. Passwords are stored only as bcrypt hashes.
-- ============================================================================

CREATE TABLE users (
  user_id       INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name     VARCHAR(120) NOT NULL,
  email         VARCHAR(254) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role          VARCHAR(16)  NOT NULL DEFAULT 'user',
  is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),

  -- FR-02: duplicate accounts are prevented on the *normalized* email, so the
  -- database itself refuses "Ada@Campus.test" when "ada@campus.test" exists.
  CONSTRAINT users_email_key            UNIQUE (email),
  CONSTRAINT users_email_normalized_chk CHECK (email = lower(email)),
  CONSTRAINT users_email_format_chk     CHECK (email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
  CONSTRAINT users_full_name_len_chk    CHECK (char_length(btrim(full_name)) BETWEEN 2 AND 120),
  -- A bcrypt hash is 60 chars; the floor guards against accidentally storing
  -- a plaintext or truncated password.
  CONSTRAINT users_password_hash_len_chk CHECK (char_length(password_hash) >= 20),
  CONSTRAINT users_role_chk             CHECK (role IN ('user', 'admin'))
);

COMMENT ON TABLE  users IS 'Registered campus users and administrators.';
COMMENT ON COLUMN users.email IS 'Stored lower-cased; uniqueness is enforced on the normalized value (NFR/FR-02).';
COMMENT ON COLUMN users.password_hash IS 'bcrypt hash. Never selected by the API response layer.';

CREATE TRIGGER trg_users_set_updated_at
  BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

-- Supports administrator listing / filtering by active state.
CREATE INDEX users_role_idx     ON users (role);
CREATE INDEX users_is_active_idx ON users (is_active) WHERE is_active = FALSE;
