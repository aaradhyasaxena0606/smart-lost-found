-- ============================================================================
-- 005_items.sql
-- Lost and found item reports (single-table inheritance on report_type).
--
-- Spatial column strategy (documented in docs/database-design.md):
--   * Type:      geography(Point, 4326)
--   * Axis order: longitude first, latitude second (X = longitude, Y = latitude)
--   * Units:     geography uses metres for ST_Distance / ST_DWithin, which is
--                what a "within N metres" campus search needs.
-- ============================================================================

CREATE TABLE items (
  item_id       INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reporter_id   INTEGER      NOT NULL,
  category_id   INTEGER      NOT NULL,
  report_type   VARCHAR(8)   NOT NULL,
  title         VARCHAR(200) NOT NULL,
  description   TEXT         NOT NULL,
  colour        VARCHAR(50),
  brand         VARCHAR(100),
  event_time    TIMESTAMPTZ  NOT NULL,
  location_name VARCHAR(200),
  location      geography(Point, 4326),
  status        VARCHAR(16)  NOT NULL DEFAULT 'open',
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
  closed_at     TIMESTAMPTZ,
  -- Soft deletion: reports are closed/hidden rather than hard-deleted so that
  -- audit history and claim history remain intact (spec 12.2).
  deleted_at    TIMESTAMPTZ,

  CONSTRAINT items_reporter_fk      FOREIGN KEY (reporter_id)
    REFERENCES users (user_id)      ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT items_category_fk      FOREIGN KEY (category_id)
    REFERENCES categories (category_id) ON DELETE RESTRICT ON UPDATE CASCADE,

  CONSTRAINT items_report_type_chk  CHECK (report_type IN ('lost', 'found')),
  CONSTRAINT items_status_chk       CHECK (status IN ('open', 'matched', 'claimed', 'returned', 'closed', 'rejected')),
  CONSTRAINT items_title_len_chk    CHECK (char_length(btrim(title)) BETWEEN 3 AND 200),
  CONSTRAINT items_description_len_chk CHECK (char_length(btrim(description)) BETWEEN 10 AND 5000),
  CONSTRAINT items_colour_len_chk   CHECK (colour IS NULL OR char_length(colour) BETWEEN 1 AND 50),
  CONSTRAINT items_brand_len_chk    CHECK (brand  IS NULL OR char_length(brand)  BETWEEN 1 AND 100),
  CONSTRAINT items_closed_at_chk    CHECK (closed_at IS NULL OR closed_at >= created_at),
  CONSTRAINT items_deleted_at_chk   CHECK (deleted_at IS NULL OR deleted_at >= created_at)
);

COMMENT ON TABLE  items IS 'Lost (report_type=lost) and found (report_type=found) reports.';
COMMENT ON COLUMN items.location IS 'geography(Point,4326); X=longitude, Y=latitude; distances in metres.';
COMMENT ON COLUMN items.deleted_at IS 'Soft-delete marker. Public queries exclude rows where this is not null.';
COMMENT ON COLUMN items.status IS 'Lifecycle status guarded by items_status_chk and fn_validate_item_status_transition().';

CREATE TRIGGER trg_items_set_updated_at
  BEFORE UPDATE ON items
  FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

-- ---------------------------------------------------------------------------
-- Status transition guard (FR-21, spec 12.4).
-- The backend validates transitions for good error messages; this trigger makes
-- the same rule impossible to bypass from raw SQL, seeds or future clients.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_validate_item_status_transition()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.status IS NOT DISTINCT FROM OLD.status THEN
    RETURN NEW;
  END IF;

  IF NOT (
       (OLD.status = 'open'     AND NEW.status IN ('matched', 'claimed', 'closed', 'rejected'))
    OR (OLD.status = 'matched'  AND NEW.status IN ('claimed', 'returned', 'closed', 'rejected'))
    OR (OLD.status = 'claimed'  AND NEW.status IN ('returned', 'closed', 'open'))
    OR (OLD.status = 'returned' AND NEW.status IN ('closed'))
    OR (OLD.status = 'closed'   AND NEW.status IN ('open'))
    OR (OLD.status = 'rejected' AND NEW.status IN ('open', 'closed'))
  ) THEN
    RAISE EXCEPTION 'Invalid item status transition from "%" to "%" (item_id=%)',
      OLD.status, NEW.status, OLD.item_id
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NEW;
END;
$$;

COMMENT ON FUNCTION fn_validate_item_status_transition() IS
  'Rejects illegal items.status transitions at the database level (spec 12.4).';

CREATE TRIGGER trg_items_validate_status_transition
  BEFORE UPDATE OF status ON items
  FOR EACH ROW EXECUTE FUNCTION fn_validate_item_status_transition();
