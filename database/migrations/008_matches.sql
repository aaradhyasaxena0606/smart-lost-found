-- ============================================================================
-- 008_matches.sql
-- Candidate lost/found pairs produced by the matching engine.
-- Component scores are stored so results are explainable and auditable.
-- ============================================================================

CREATE TABLE matches (
  match_id        INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lost_item_id    INTEGER      NOT NULL,
  found_item_id   INTEGER      NOT NULL,
  attribute_score NUMERIC(5,2) NOT NULL,
  time_score      NUMERIC(5,2) NOT NULL,
  spatial_score   NUMERIC(5,2),
  ai_score        NUMERIC(5,2),
  overall_score   NUMERIC(5,2) NOT NULL,
  match_status    VARCHAR(16)  NOT NULL DEFAULT 'suggested',
  -- Non-sensitive explanation objects only, e.g.
  --   [{"code":"category_match","label":"Same category","weight":0.40}]
  -- Private verification hints and claim evidence must never be written here.
  match_reasons   JSONB        NOT NULL DEFAULT '[]'::jsonb,
  created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),

  CONSTRAINT matches_lost_item_fk  FOREIGN KEY (lost_item_id)
    REFERENCES items (item_id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT matches_found_item_fk FOREIGN KEY (found_item_id)
    REFERENCES items (item_id) ON DELETE CASCADE ON UPDATE CASCADE,

  -- One row per unordered... actually per ordered (lost, found) pair: duplicates
  -- are impossible even if two requests recalculate concurrently (spec 13.1/9).
  CONSTRAINT matches_pair_key UNIQUE (lost_item_id, found_item_id),
  CONSTRAINT matches_distinct_items_chk CHECK (lost_item_id <> found_item_id),
  CONSTRAINT matches_status_chk CHECK (match_status IN ('suggested', 'dismissed', 'claimed', 'resolved')),

  CONSTRAINT matches_attribute_score_chk CHECK (attribute_score >= 0 AND attribute_score <= 100),
  CONSTRAINT matches_time_score_chk      CHECK (time_score      >= 0 AND time_score      <= 100),
  CONSTRAINT matches_spatial_score_chk   CHECK (spatial_score IS NULL OR (spatial_score >= 0 AND spatial_score <= 100)),
  CONSTRAINT matches_ai_score_chk        CHECK (ai_score        IS NULL OR (ai_score        >= 0 AND ai_score        <= 100)),
  CONSTRAINT matches_overall_score_chk   CHECK (overall_score   >= 0 AND overall_score   <= 100),
  CONSTRAINT matches_reasons_array_chk   CHECK (jsonb_typeof(match_reasons) = 'array')
);

COMMENT ON TABLE  matches IS 'Ranked candidate lost/found pairs with explainable component scores (FR-13, FR-14).';
COMMENT ON COLUMN matches.overall_score IS 'Weighted 0-100 ranking score over the *available* components; never proof of ownership (NFR-15).';

CREATE TRIGGER trg_matches_set_updated_at
  BEFORE UPDATE ON matches
  FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

-- ---------------------------------------------------------------------------
-- DB safeguard for spec 12.1: "enforce that the referenced reports are
-- respectively lost and found". Application code validates this too; the
-- trigger guarantees it for raw SQL, seeds and future clients.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_validate_match_report_types()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  v_lost_type  VARCHAR(8);
  v_found_type VARCHAR(8);
BEGIN
  SELECT report_type INTO v_lost_type  FROM items WHERE item_id = NEW.lost_item_id;
  SELECT report_type INTO v_found_type FROM items WHERE item_id = NEW.found_item_id;

  IF v_lost_type IS NULL OR v_lost_type <> 'lost' THEN
    RAISE EXCEPTION 'matches.lost_item_id (%) must reference a report with report_type = ''lost''', NEW.lost_item_id
      USING ERRCODE = 'check_violation';
  END IF;

  IF v_found_type IS NULL OR v_found_type <> 'found' THEN
    RAISE EXCEPTION 'matches.found_item_id (%) must reference a report with report_type = ''found''', NEW.found_item_id
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NEW;
END;
$$;

COMMENT ON FUNCTION fn_validate_match_report_types() IS
  'Enforces that a match always pairs one lost report with one found report.';

CREATE TRIGGER trg_matches_validate_report_types
  BEFORE INSERT OR UPDATE OF lost_item_id, found_item_id ON matches
  FOR EACH ROW EXECUTE FUNCTION fn_validate_match_report_types();
