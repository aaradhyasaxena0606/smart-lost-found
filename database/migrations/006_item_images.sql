-- ============================================================================
-- 006_item_images.sql
-- Optional item images (FR-09). Only server-generated storage keys are stored;
-- the original client filename is never trusted or persisted as a path.
-- ============================================================================

CREATE TABLE item_images (
  image_id    INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id     INTEGER      NOT NULL,
  storage_key VARCHAR(120) NOT NULL,
  mime_type   VARCHAR(64)  NOT NULL,
  byte_size   INTEGER      NOT NULL,
  alt_text    VARCHAR(200),
  uploaded_at TIMESTAMPTZ  NOT NULL DEFAULT now(),

  CONSTRAINT item_images_item_fk FOREIGN KEY (item_id)
    REFERENCES items (item_id) ON DELETE CASCADE ON UPDATE CASCADE,

  CONSTRAINT item_images_storage_key_key UNIQUE (storage_key),
  -- Uploads are treated as untrusted input: only raster image types are allowed
  -- and the stored file is never served as executable content (spec 16).
  CONSTRAINT item_images_mime_chk CHECK (mime_type IN ('image/jpeg', 'image/png', 'image/webp')),
  CONSTRAINT item_images_size_chk CHECK (byte_size > 0 AND byte_size <= 10485760),
  CONSTRAINT item_images_storage_key_chk CHECK (storage_key ~ '^[A-Za-z0-9._-]+$')
);

COMMENT ON TABLE item_images IS 'Public-safe item image references; one item may have many images.';
