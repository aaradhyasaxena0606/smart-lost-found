-- ============================================================================
-- 011_audit_logs.sql
-- Append-only audit trail for important user and administrator actions
-- (FR-24). Rows are never updated or deleted by the application.
-- ============================================================================

CREATE TABLE audit_logs (
  audit_id      BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_user_id INTEGER,
  action        VARCHAR(60)  NOT NULL,
  entity_type   VARCHAR(40)  NOT NULL,
  entity_id     INTEGER,
  -- Safe, non-secret details only: no passwords, tokens, private evidence or
  -- private verification hints (NFR-14).
  metadata      JSONB        NOT NULL DEFAULT '{}'::jsonb,
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),

  -- ON DELETE SET NULL keeps history even if an account is removed; the audit
  -- record itself is preserved (spec 12.2 "preserve audit history").
  CONSTRAINT audit_logs_actor_fk FOREIGN KEY (actor_user_id)
    REFERENCES users (user_id) ON DELETE SET NULL ON UPDATE CASCADE,

  CONSTRAINT audit_logs_action_len_chk CHECK (char_length(btrim(action)) BETWEEN 3 AND 60),
  CONSTRAINT audit_logs_entity_len_chk CHECK (char_length(btrim(entity_type)) BETWEEN 3 AND 40),
  CONSTRAINT audit_logs_metadata_object_chk CHECK (jsonb_typeof(metadata) = 'object')
);

COMMENT ON TABLE audit_logs IS 'Append-only audit trail; application only inserts rows.';

CREATE INDEX audit_logs_actor_idx       ON audit_logs (actor_user_id);
CREATE INDEX audit_logs_created_at_idx  ON audit_logs (created_at DESC);
CREATE INDEX audit_logs_entity_idx      ON audit_logs (entity_type, entity_id);
