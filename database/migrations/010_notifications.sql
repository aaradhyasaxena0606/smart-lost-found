-- ============================================================================
-- 010_notifications.sql
-- In-app notifications for key workflow events (FR-23).
-- ============================================================================

CREATE TABLE notifications (
  notification_id  INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          INTEGER      NOT NULL,
  notification_type VARCHAR(40) NOT NULL,
  title            VARCHAR(200) NOT NULL,
  message          VARCHAR(1000) NOT NULL,
  related_item_id  INTEGER,
  related_claim_id INTEGER,
  is_read          BOOLEAN      NOT NULL DEFAULT FALSE,
  created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),

  CONSTRAINT notifications_user_fk FOREIGN KEY (user_id)
    REFERENCES users (user_id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT notifications_item_fk FOREIGN KEY (related_item_id)
    REFERENCES items (item_id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT notifications_claim_fk FOREIGN KEY (related_claim_id)
    REFERENCES claims (claim_id) ON DELETE CASCADE ON UPDATE CASCADE,

  CONSTRAINT notifications_type_chk CHECK (notification_type IN (
    'item_matched',
    'claim_submitted',
    'claim_approved',
    'claim_rejected',
    'claim_withdrawn',
    'item_returned',
    'item_moderated',
    'item_closed'
  )),
  CONSTRAINT notifications_title_len_chk   CHECK (char_length(btrim(title)) BETWEEN 1 AND 200),
  CONSTRAINT notifications_message_len_chk CHECK (char_length(btrim(message)) BETWEEN 1 AND 1000)
);

COMMENT ON TABLE notifications IS 'User-facing in-app notifications; never contains private verification or claim evidence.';

CREATE INDEX notifications_user_created_idx ON notifications (user_id, created_at DESC);
-- Partial index for the common "unread badge" query.
CREATE INDEX notifications_unread_idx       ON notifications (user_id) WHERE is_read = FALSE;
