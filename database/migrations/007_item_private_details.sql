-- ============================================================================
-- 007_item_private_details.sql
-- Private verification data for a report (e.g. "initials scratched under the
-- lid"). At most one row per item. This data is NEVER included in public item
-- responses (FR-26). See docs/security.md for the access policy.
-- ============================================================================

CREATE TABLE item_private_details (
  private_detail_id INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id           INTEGER      NOT NULL,
  verification_hint VARCHAR(500),
  created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),

  -- 1:0..1 relationship with items, enforced by the unique constraint.
  CONSTRAINT item_private_details_item_key UNIQUE (item_id),
  CONSTRAINT item_private_details_item_fk  FOREIGN KEY (item_id)
    REFERENCES items (item_id) ON DELETE CASCADE ON UPDATE CASCADE
);

COMMENT ON TABLE item_private_details IS
  'Access-restricted ownership verification hint. Excluded from v_public_items and all public API responses.';

CREATE TRIGGER trg_item_private_details_set_updated_at
  BEFORE UPDATE ON item_private_details
  FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();
